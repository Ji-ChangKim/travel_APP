export const pages = rows.map(([number, key, name, parent, view, group]) => {
  // 번호는 순서와 무관하게 유지해 이후 화면 추가에도 파일명이 바뀌지 않는다.
  return {
    number,
    key,
    name,
    title: titles[key] || name,
    parent,
    view,
    group,
    file: `${String(number).padStart(3, '0')}_${name}`,
    kind:
      group === 'popup'
        ? 'popup'
        : group === 'exception'
          ? 'exception'
          : parent
            ? 'child'
            : 'major',
  };
});

// 실제 검토 목록에서 단일 화면 정의를 찾는다.
export function pageByKey(key) {
  // 정의되지 않은 화면의 버튼을 정상 화면처럼 연결하지 않는다.
  return pages.find((page) => {
    // 화면 키는 목록 전체에서 유일하다.
    return page.key === key;
  });
}
